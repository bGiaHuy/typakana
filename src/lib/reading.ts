import { toRomaji } from "wanakana"

export interface ReadingPassage {
	id: string
	title: string
	text: string
	reading: string
}

export interface ReadingToken {
	display: string
	expected: string
	separator: boolean
	inputIndex?: number
}

const wordPattern = /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}A-Za-z0-9ー]+/gu
export function passageTokens(passage: ReadingPassage): ReadingToken[] {
	const sourceWords = [...passage.text.matchAll(wordPattern)]
	const readingWords = [...passage.reading.matchAll(wordPattern)]
	const tokens: ReadingToken[] = []
	let sourceCursor = 0

	sourceWords.forEach((sourceWord, index) => {
		const separator = passage.text.slice(sourceCursor, sourceWord.index)
		if (separator) tokens.push({ display: separator, expected: "", separator: true })
		tokens.push({
			display: sourceWord[0],
			expected: toRomaji(readingWords[index]?.[0] ?? ""),
			separator: false
		})
		sourceCursor = (sourceWord.index ?? 0) + sourceWord[0].length
	})

	const trailingSeparator = passage.text.slice(sourceCursor)
	if (trailingSeparator) tokens.push({ display: trailingSeparator, expected: "", separator: true })
	let inputIndex = 0
	return tokens.map((token) =>
		token.separator ? token : { ...token, inputIndex: inputIndex++ }
	)
}

